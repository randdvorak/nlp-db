"""<project>/data/catalog.json -> Sources/dbq/EmbeddedData.swift, so the binary needs no data files.

  python3 scripts/embed-data.py ../databases/<name>     (or set DBQ_PROJECT)

Make catalog.json first: python3 engine/catalog_json.py --project databases/<name>. It carries
the project's name, system prompt, default connection and model file name; dbq builds its plan
grammar from it (PlanGrammar.swift).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def raw(text):
    # Swift raw multi-line string: ##"""...."""## never ends early on " or #
    assert '"""##' not in text
    return '##"""\n' + text.rstrip("\n") + '\n"""##'


project = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("DBQ_PROJECT")
if not project:
    sys.exit("usage: embed-data.py PROJECT_DIR (or set DBQ_PROJECT)")
src = os.path.join(project, "data", "catalog.json")
if not os.path.exists(src):
    sys.exit(f"no {src}: run engine/catalog_json.py --project {project} first")
catalog = open(src, encoding="utf-8").read()
with open(os.path.join(ROOT, "Sources", "dbq", "EmbeddedData.swift"), "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/embed-data.py; do not edit.\n")
    f.write("enum EmbeddedData {\n")
    f.write(f"    static let catalog = {raw(catalog)}\n")
    f.write("}\n")
print(f"wrote Sources/dbq/EmbeddedData.swift from {src}")
